// Dump the seeded demo database as plain SQL (INSERT statements + sequence
// resets) so it can be applied to the hosted Supabase project via the
// management connector. Usage:
//   node scripts/pg-dump.mjs > scripts/seed-pg.sql
// Requires @electric-sql/pglite (dev-only, `npm i --no-save @electric-sql/pglite`).
// Everything runs against a throwaway in-memory Postgres — the local SQLite
// data directory is never touched.
process.env.DATABASE_URL = 'pglite://memory';

// Seed logs to stderr so stdout stays a clean SQL script.
const realLog = console.log;
console.log = (...args) => console.error(...args);
await import('../server/seed.js');
const { all, exec } = await import('../server/db.js');
console.log = realLog;

const TABLES = [
  'users', 'settings', 'clients', 'connected_accounts', 'conversations',
  'messages', 'attachments', 'activity_log', 'meetings', 'notifications',
];
const ID_TABLES = ['users', 'clients', 'connected_accounts', 'conversations', 'messages', 'attachments', 'activity_log', 'meetings', 'notifications'];

const lit = (v) => {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'number') return String(v);
  if (typeof v === 'bigint') return String(v);
  if (typeof v === 'boolean') return v ? '1' : '0';
  return `'${String(v).replace(/'/g, "''")}'`;
};

const out = [];
out.push('-- Relay demo seed (generated by scripts/pg-dump.mjs) — safe to re-run on an empty database');
out.push('BEGIN;');
for (const table of TABLES) {
  const rows = await all(`SELECT * FROM ${table}`);
  for (const row of rows) {
    const cols = Object.keys(row);
    const vals = cols.map((c) => lit(row[c]));
    const overriding = cols.includes('id') ? ' OVERRIDING SYSTEM VALUE' : '';
    out.push(`INSERT INTO ${table} (${cols.join(', ')})${overriding} VALUES (${vals.join(', ')});`);
  }
}
out.push('COMMIT;');
// Realign IDENTITY sequences with the loaded max(id)
for (const table of ID_TABLES) {
  out.push(`SELECT setval(pg_get_serial_sequence('${table}', 'id'), COALESCE((SELECT MAX(id) FROM ${table}), 1));`);
}

console.log(out.join('\n'));
await exec('SELECT 1'); // keep the process honest about flush completion
process.exit(0);
